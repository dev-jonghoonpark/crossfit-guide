/** F(가까운 쪽) 관절만 적어주면 B(먼 쪽)를 자동으로 만들어 준다. */
function pose(over = {}, dx = -8, dy = 0) {
  const p = { ...BASE, ...over };
  for (const part of ['elbow', 'wrist', 'knee', 'ankle', 'toe', 'heel']) {
    const b = part + 'B';
    if (!p[b]) p[b] = [p[part + 'F'][0] + dx, p[part + 'F'][1] + dy];
  }
  return p;
}

