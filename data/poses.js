/**
 * 스켈레톤 포즈 라이브러리 (측면 뷰 / 오른쪽을 바라봄)
 *
 * 좌표계: viewBox "0 0 260 330", y는 아래로 증가. 바닥선 y = 300.
 * 관절 이름 규칙
 *   - head / neck / shoulder / hip : 몸통 중심선
 *   - ~F : 카메라에 가까운 쪽 팔·다리 (진하게 그려짐)
 *   - ~B : 반대쪽 팔·다리 (연하게 그려짐 → 입체감)
 *
 * 도구(prop) — 전부 [x, y] 라서 구간 사이 보간이 그대로 먹는다. 없으면 안 그려진다.
 *   bar        바벨 중심 (측면에서 원판은 원으로 보임)
 *   dbF / dbB  덤벨 (가까운 손 / 먼 손)
 *   ball       메디신볼 · 월볼
 *   rig        철봉
 *   ringF/ringB 링 (천장에서 스트랩이 내려온다)
 *   box        플라이오 박스 [중심x, 윗면y]
 *   bench      벤치 [중심x, 패드 윗면y]
 *   riserF/riserB 손 받침 (원판·매트)
 *   wall       벽 [x, 미사용] / target 월볼 타깃 [x, y]
 *   rower      로잉 머신 시트 [x, y] (레일·플라이휠·체인은 자동)
 *   ropeAngle  줄넘기 줄의 각도(도). 계속 누적되는 값이라 720 = 두 바퀴
 *
 * 새 동작을 추가할 때는 여기에 포즈를 만들고 movements.js 에서 이름으로 참조하면 된다.
 *
 * ⚠️ 사람 크기는 기본적으로 전 동작이 같지만, 월볼(wb*)과 바 뮤스클업(bmu*) 두 계열만
 *    0.6~0.7배로 줄여 그린다. 월볼 타깃(10ft)이나 뮤스클업 서포트 자세가
 *    같은 크기로는 화면(y=0~330) 밖으로 나가 버려서, 줄이지 않으면
 *    "머리 위로 살짝 던지는" 그림이 되어 실제 동작과 달라지기 때문이다.
 *    줄인 계열은 pose() 의 두 번째 인자(dx)로 먼 쪽 팔·다리 간격도 같이 줄인다.
 */

